export const galleryPhotos = photoAlbums.flatMap((album) => album.photos.map((photo) => photo.src));

export const getAlbum = (albumId) => photoAlbums.find((album) => album.id === albumId);

export const getAlbumPhotos = (albumId, limit) => {
  const album = getAlbum(albumId);
  const photos = album ? album.photos : [];
  return typeof limit === 'number' ? photos.slice(0, limit) : photos;
};

export const getFeaturedPhotos = (albumIds, limit = 4) => albumIds
  .flatMap((albumId) => getAlbumPhotos(albumId))
  .slice(0, limit);
